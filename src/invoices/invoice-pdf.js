import PDFDocument from 'pdfkit';
import { WEEKDAY_NAMES } from '../common/utils/dates';

const MARGIN = 50;
const MUTED = '#666666';
const RULE = '#DDDDDD';

const formatMoney = (amount, currency) =>
  new Intl.NumberFormat(currency === 'INR' ? 'en-IN' : 'en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(Number(amount)) + ` ${currency}`;

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const formatDay = (iso) => {
  const [y, m, d] = iso.split('-');
  return `${d} ${MONTHS[Number(m) - 1]} ${y}`;
};

/**
 * Renders the invoice PDF and resolves to a Buffer.
 * @param {object} invoice  { invoiceNumber, issuedAt, status, generatedBy, calc, employee, project, company }
 */
export function renderInvoicePdf(invoice) {
  const { calc, employee, project, company } = invoice;
  const currency = calc.currency;
  const doc = new PDFDocument({ size: 'A4', margin: MARGIN, info: { Title: invoice.invoiceNumber } });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const done = new Promise((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  const width = doc.page.width - MARGIN * 2;
  const rule = () => {
    doc.moveDown(0.4).strokeColor(RULE).lineWidth(1)
      .moveTo(MARGIN, doc.y).lineTo(MARGIN + width, doc.y).stroke().moveDown(0.6);
  };
  const heading = (text) =>
    doc.font('Helvetica-Bold').fontSize(11).fillColor('black').text(text, MARGIN, doc.y).moveDown(0.3);
  const row = (label, value, { bold = false } = {}) => {
    const y = doc.y;
    doc.font('Helvetica').fontSize(9.5).fillColor(MUTED).text(label, MARGIN, y, { width: width * 0.55 });
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fillColor('black')
      .text(String(value ?? '—'), MARGIN + width * 0.55, y, { width: width * 0.45, align: 'right' });
    doc.x = MARGIN;
    doc.moveDown(0.25);
  };

  // Header
  doc.font('Helvetica-Bold').fontSize(18).fillColor('black').text(company.name, MARGIN, MARGIN);
  doc.font('Helvetica').fontSize(9).fillColor(MUTED);
  for (const line of company.addressLines || []) doc.text(line);
  if (company.email) doc.text(company.email);
  doc.font('Helvetica-Bold').fontSize(14).fillColor('black').text('SALARY INVOICE', MARGIN, MARGIN, { align: 'right' });
  doc.font('Helvetica').fontSize(9.5)
    .text(invoice.invoiceNumber, { align: 'right' })
    .text(`Issued ${formatDay(invoice.issuedAt.slice(0, 10))}`, { align: 'right' })
    .text(`Status: ${invoice.status.toUpperCase()}`, { align: 'right' });
  doc.x = MARGIN;
  doc.y = Math.max(doc.y, MARGIN + 60);
  rule();

  heading('Employee');
  row('Name', employee.full_name);
  row('Employee ID', employee.employee_code);
  row('Designation', employee.designation);
  row('Department', employee.department);
  rule();

  heading('Project');
  row('Project', project.name);
  row('Client', project.client_name);
  row('Billing period', `${formatDay(calc.periodStart)} – ${formatDay(calc.periodEnd)}`);
  row('Weekend', calc.weekendDays.map((d) => WEEKDAY_NAMES[d]).join(', ') || 'None');
  rule();

  heading('Attendance summary');
  row('Working days in period', calc.workingDays);
  row('Present', calc.attendance.present);
  row('Work from home', calc.attendance.wfh);
  row('Half days', calc.attendance.halfDay);
  row('Paid leave', calc.attendance.paidLeave);
  row('Absent', calc.attendance.absent);
  row('Unmarked (counted as 0)', calc.attendance.unmarked);
  if (calc.attendance.notAssigned) row('Outside assignment', calc.attendance.notAssigned);
  row(
    'Holidays in period',
    calc.holidays.length ? calc.holidays.map((h) => `${formatDay(h.date)} ${h.name}`).join('; ') : 'None',
  );
  rule();

  heading('Calculation');
  for (const seg of calc.salarySegments) {
    const range = calc.salarySegments.length > 1 ? ` (${formatDay(seg.from)} – ${formatDay(seg.to)})` : '';
    row(`Monthly salary${range}`, formatMoney(seg.monthlyAmount, currency));
    row(`Per-day rate (÷ ${calc.workingDays} working days)`, formatMoney(seg.perDayRate, currency));
    if (calc.salarySegments.length > 1) row('Payable days at this rate', seg.payableDays);
  }
  row('Payable days', calc.payableDays);
  row('Gross pay', formatMoney(calc.grossAmount, currency), { bold: true });
  for (const adj of calc.adjustments) {
    const sign = adj.type === 'deduction' ? '-' : '+';
    row(`${adj.type === 'deduction' ? 'Deduction' : 'Allowance'}: ${adj.label}`, `${sign} ${formatMoney(adj.amount, currency)}`);
  }
  doc.moveDown(0.3);
  row('Net payable', formatMoney(calc.netAmount, currency), { bold: true });
  rule();

  // Footer
  doc.font('Helvetica').fontSize(8).fillColor(MUTED)
    .text(`Generated by ${invoice.generatedBy} on ${new Date(invoice.issuedAt).toUTCString()}`, MARGIN, doc.y, { width })
    .text('This is a computer-generated invoice; no signature is required.', { width });

  doc.end();
  return done;
}
